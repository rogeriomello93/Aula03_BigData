sub = prim_num - seg_num
mult = prim_num * seg_num
div = prim_num / seg_num

print(f'\nA soma dos numeros é {soma}')
print(f'A subração dos numeros é {sub}')
print(f'A multiplicação dos numeros é {mult}')
print(f'A divisão dos numeros é {div}')

